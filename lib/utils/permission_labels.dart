import '../l10n/l10n.dart';

/// Libellé simple d'une permission Android courante, dans la langue [l],
/// ex : android.permission.CAMERA → « Utiliser l'appareil photo ».
/// Null si la permission est inconnue.
String? permissionLabel(AppLocalizations l, String permission) {
  const prefix = 'android.permission.';
  if (!permission.startsWith(prefix)) return null;
  // La clé est le nom court, sans « android.permission. ».
  return switch (permission.substring(prefix.length)) {
    'READ_SMS' => l.permReadSms,
    'RECEIVE_SMS' => l.permReceiveSms,
    'SEND_SMS' => l.permSendSms,
    'RECEIVE_MMS' => l.permReceiveMms,
    'READ_CALL_LOG' => l.permReadCallLog,
    'WRITE_CALL_LOG' => l.permWriteCallLog,
    'CALL_PHONE' => l.permCallPhone,
    'ANSWER_PHONE_CALLS' => l.permAnswerPhoneCalls,
    'READ_PHONE_STATE' => l.permReadPhoneState,
    'READ_PHONE_NUMBERS' => l.permReadPhoneNumbers,
    'READ_CONTACTS' => l.permReadContacts,
    'WRITE_CONTACTS' => l.permWriteContacts,
    'GET_ACCOUNTS' => l.permGetAccounts,
    'READ_CALENDAR' => l.permReadCalendar,
    'WRITE_CALENDAR' => l.permWriteCalendar,
    'RECORD_AUDIO' => l.permRecordAudio,
    'CAMERA' => l.permCamera,
    'BODY_SENSORS' => l.permBodySensors,
    'BODY_SENSORS_BACKGROUND' => l.permBodySensorsBackground,
    'ACTIVITY_RECOGNITION' => l.permActivityRecognition,
    'ACCESS_FINE_LOCATION' => l.permAccessFineLocation,
    'ACCESS_COARSE_LOCATION' => l.permAccessCoarseLocation,
    'ACCESS_BACKGROUND_LOCATION' => l.permAccessBackgroundLocation,
    'ACCESS_MEDIA_LOCATION' => l.permAccessMediaLocation,
    'READ_EXTERNAL_STORAGE' => l.permReadExternalStorage,
    'WRITE_EXTERNAL_STORAGE' => l.permWriteExternalStorage,
    'MANAGE_EXTERNAL_STORAGE' => l.permManageExternalStorage,
    'READ_MEDIA_IMAGES' => l.permReadMediaImages,
    'READ_MEDIA_VIDEO' => l.permReadMediaVideo,
    'READ_MEDIA_AUDIO' => l.permReadMediaAudio,
    'READ_MEDIA_VISUAL_USER_SELECTED' => l.permReadMediaVisualUserSelected,
    'BLUETOOTH' => l.permBluetooth,
    'BLUETOOTH_CONNECT' => l.permBluetoothConnect,
    'BLUETOOTH_SCAN' => l.permBluetoothScan,
    'NEARBY_WIFI_DEVICES' => l.permNearbyWifiDevices,
    'NFC' => l.permNfc,
    'INTERNET' => l.permInternet,
    'ACCESS_NETWORK_STATE' => l.permAccessNetworkState,
    'ACCESS_WIFI_STATE' => l.permAccessWifiState,
    'CHANGE_WIFI_STATE' => l.permChangeWifiState,
    'SYSTEM_ALERT_WINDOW' => l.permSystemAlertWindow,
    'POST_NOTIFICATIONS' => l.permPostNotifications,
    'REQUEST_INSTALL_PACKAGES' => l.permRequestInstallPackages,
    'REQUEST_DELETE_PACKAGES' => l.permRequestDeletePackages,
    'QUERY_ALL_PACKAGES' => l.permQueryAllPackages,
    'PACKAGE_USAGE_STATS' => l.permPackageUsageStats,
    'RECEIVE_BOOT_COMPLETED' => l.permReceiveBootCompleted,
    'FOREGROUND_SERVICE' => l.permForegroundService,
    'WAKE_LOCK' => l.permWakeLock,
    'VIBRATE' => l.permVibrate,
    'USE_BIOMETRIC' => l.permUseBiometric,
    'USE_FINGERPRINT' => l.permUseFingerprint,
    'SCHEDULE_EXACT_ALARM' => l.permScheduleExactAlarm,
    'USE_FULL_SCREEN_INTENT' => l.permUseFullScreenIntent,
    _ => null,
  };
}
